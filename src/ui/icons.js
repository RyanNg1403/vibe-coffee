export function iconSvg(name, className = 'icon') {
  const body = ICONS[name];
  if (!body) return '';
  return wrap(body, 'currentColor').replace('<svg ', `<svg class="${className}" aria-hidden="true" focusable="false" `);
}

export function iconCss() {
  const vars = Object.entries(ICONS)
    .map(([name, body]) => `--i-${name}:url("data:image/svg+xml,${encodeURIComponent(wrap(body, '#000'))}");`)
    .join('');
  return `:root{${vars}}`;
}
